/**
 * EXPERIMENTAL — `rune serve install`
 *
 * Writes a systemd unit that keeps `rune serve` running. Default is a user
 * unit (~/.config/systemd/user/rune-serve.service, no root needed);
 * `--print` writes the unit to stdout instead, for /etc/systemd/system.
 * It never runs systemctl itself — it prints the commands to run.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

/** Flags forwarded from `rune serve install …` to the service's `rune serve`. */
export const FORWARDED_FLAGS = [
  'port',
  'host',
  'skills-dir',
  'pro-root',
  'business-root',
  'no-tiers',
  'rate-limit',
  'max-bytes',
  'trust-proxy',
  'allow-query-key',
  'config',
  'name',
  'runner',
  'runner-timeout',
  'runner-concurrency',
  'tunnel',
];

/** Quote one ExecStart word for systemd. */
export function systemdQuote(word) {
  const s = String(word);
  if (/[\n\r\0]/.test(s)) throw new Error(`Refusing a value with a newline: ${JSON.stringify(s)}`);
  if (/^[A-Za-z0-9_@+=:,./-]+$/.test(s)) return s;
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '$$$$').replace(/%/g, '%%')}"`;
}

/**
 * @param {{ nodePath: string, runeBin: string, args: object, env?: NodeJS.ProcessEnv, user?: boolean }} opts
 * @returns {string}
 */
export function buildUnit({ nodePath, runeBin, args = {}, env = process.env, user = true }) {
  const argv = [nodePath, runeBin, 'serve'];
  for (const flag of FORWARDED_FLAGS) {
    const v = args[flag];
    if (v === undefined || v === false) continue;
    if (v === true) argv.push(`--${flag}`);
    else
      argv.push(
        `--${flag}`,
        String(flag.endsWith('-root') || flag === 'skills-dir' || flag === 'config' ? resolveList(v) : v),
      );
  }
  const envLines = [];
  for (const k of ['RUNE_PRO_ROOT', 'RUNE_BUSINESS_ROOT', 'RUNE_SERVE_CONFIG']) {
    if (env[k]) envLines.push(`Environment=${systemdQuote(`${k}=${env[k]}`)}`);
  }
  // A runner needs the agent CLI on PATH.
  if (args.runner || args.tunnel)
    envLines.push(`Environment=${systemdQuote(`PATH=${env.PATH || '/usr/local/bin:/usr/bin:/bin'}`)}`);
  return [
    '# Generated by `rune serve install` — Rune skill server (MCP)',
    '[Unit]',
    'Description=Rune skill server (MCP)',
    'After=network-online.target',
    'Wants=network-online.target',
    '',
    '[Service]',
    'Type=simple',
    `ExecStart=${argv.map(systemdQuote).join(' ')}`,
    ...envLines,
    'Restart=on-failure',
    'RestartSec=5',
    'NoNewPrivileges=true',
    'PrivateTmp=true',
    '',
    '[Install]',
    `WantedBy=${user ? 'default.target' : 'multi-user.target'}`,
    '',
  ].join('\n');
}

function resolveList(v) {
  return String(v)
    .split(',')
    .map((p) => path.resolve(p.trim()))
    .join(',');
}

/**
 * Write (or print) the unit.
 * @returns {{ unit: string, unitPath: string|null, next: string[] }}
 */
export function installService({ nodePath, runeBin, args = {}, homedir = os.homedir(), env = process.env }) {
  const user = !args.print;
  const unit = buildUnit({ nodePath, runeBin, args, env, user });
  if (args.print) {
    return {
      unit,
      unitPath: null,
      next: [
        'Save the unit above as /etc/systemd/system/rune-serve.service (add User=<account> under [Service]), then:',
        'sudo systemctl daemon-reload && sudo systemctl enable --now rune-serve',
      ],
    };
  }
  const dir = path.join(homedir, '.config', 'systemd', 'user');
  mkdirSync(dir, { recursive: true });
  const unitPath = path.join(dir, 'rune-serve.service');
  writeFileSync(unitPath, unit);
  return {
    unit,
    unitPath,
    next: [
      'systemctl --user daemon-reload && systemctl --user enable --now rune-serve',
      `loginctl enable-linger ${os.userInfo().username}   # keep it running after you log out`,
      'journalctl --user -u rune-serve -f                # logs',
    ],
  };
}
